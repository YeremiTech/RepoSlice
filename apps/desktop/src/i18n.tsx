const dictionaries: Record<Language, Record<string, string>> = { es, en };

type I18nContextValue = {
  language: Language;
  setLanguage: (language: Language) => void;
  toggleLanguage: () => void;
  t: (key: string, vars?: Vars) => string;
  formatDateTime: (milliseconds: number) => string;
  formatDate: (milliseconds: number) => string;
  locale: string;
};

const I18nContext = createContext<I18nContextValue | null>(null);

function interpolate(value: string, vars?: Vars): string {
  if (!vars) return value;
  return value.replace(/\{(\w+)\}/g, (_, key: string) => String(vars[key] ?? `{${key}}`));
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(() => {
    const stored = typeof window !== "undefined" ? window.localStorage.getItem(STORAGE_KEY) : null;
    return stored === "en" ? "en" : "es";
  });

  useEffect(() => {
    window.localStorage.setItem(STORAGE_KEY, language);
    document.documentElement.lang = language;
  }, [language]);

  const value = useMemo<I18nContextValue>(() => {
    const locale = language === "es" ? "es-PE" : "en-US";
    return {
      language,
      locale,
      setLanguage: setLanguageState,
      toggleLanguage: () => setLanguageState((current) => current === "es" ? "en" : "es"),
      t: (key, vars) => interpolate(dictionaries[language][key] ?? dictionaries.es[key] ?? key, vars),
      formatDateTime: (milliseconds) => milliseconds ? new Intl.DateTimeFormat(locale, { dateStyle: "short", timeStyle: "medium" }).format(new Date(milliseconds)) : "—",
      formatDate: (milliseconds) => milliseconds ? new Intl.DateTimeFormat(locale, { dateStyle: "medium", timeStyle: "short" }).format(new Date(milliseconds)) : "—"
    };
  }, [language]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
  const context = useContext(I18nContext);
  if (!context) throw new Error("useI18n must be used inside LanguageProvider");
  return context;
}

export function translateRole(role: string | undefined, t: I18nContextValue["t"]): string {
  const normalized = role?.trim().toLowerCase() ?? "";
  if (normalized.includes("frontend")) return "Frontend";
  if (normalized.includes("backend")) return "Backend";
  if (normalized.includes("fullstack")) return "Fullstack";
  if (normalized.includes("library")) return t("common.language") === "Language" ? "Library" : "Librería";
  if (normalized.includes("infra") || normalized.includes("platform")) return t("common.language") === "Language" ? "Infrastructure" : "Infraestructura";
  return t("common.unknown");
}

