export function translateDiagnosticMessage(code: string, fallback: string, t: I18nContextValue["t"]): string {
  const key = `diagnostic.${code}`;
  const variables: Vars = {};
  if (code === "text-index-memory-limit") {
    const match = fallback.match(/(\d+)\s+MiB/i);
    if (match) variables.limit = match[1];
  } else if (code === "component-index-limit") {
    const match = fallback.match(/limited to\s+(\d+)\s+of\s+(\d+)/i);
    if (match) { variables.limit = match[1]; variables.total = match[2]; }
  } else if (code === "framework-evidence-insufficient") {
    const adapter = fallback.match(/adapter\s+([^\s]+)\s+produced/i);
    const observed = fallback.match(/^(.+?)\s+was observed by/i);
    variables.framework = adapter?.[1] ?? observed?.[1] ?? "framework";
  } else if (code === "framework-no-static-entrypoints") {
    const framework = fallback.match(/^(.+?)\s+was detected/i);
    variables.framework = framework?.[1] ?? "framework";
  }
  const translated = t(key, variables);
  return translated === key ? fallback : translated;
}

export function translateAnalysisMessage(message: string, t: I18nContextValue["t"]): string {
  const normalized = message.trim();
  if (normalized === "Analysis completed and graph integrity is clean") return t("analysis.message.completed");
  if (normalized === "Analysis completed with non-blocking warnings") return t("analysis.message.completedWarnings");
  if (normalized === "Analysis completed with integrity errors or error diagnostics") return t("analysis.message.partial");
  if (normalized.toLowerCase().includes("failed")) return t("analysis.message.failed");
  return message;
}


export function translateEngineErrorDetail(detail: string, t: I18nContextValue["t"]): string {
  if (detail.includes("Only repositories cloned and managed by RepoSlice can be updated")) return t("projects.updateManagedOnly");
  if (detail.includes("Managed repository has local changes")) return t("engineError.repositoryDirty");
  if (detail.includes("Analysis was cancelled")) return t("engineError.analysisCancelled");
  const normalized = detail.trim();
  if (normalized.includes("No analysis is loaded for this workspace")) return t("engineError.analysisNotLoaded");
  if (normalized.includes("Desktop analysis cache is unavailable")) return t("engineError.cacheUnavailable");
  if (normalized.includes("Repository URL is invalid")) return t("engineError.invalidRepositoryUrl");
  if (normalized.includes("Git clone failed")) return t("engineError.cloneFailed");
  if (normalized.includes("Workspace repositories changed while analysis was running")) return t("engineError.workspaceChangedDuringAnalysis");
  if (normalized.includes("changed while analysis was running")) return t("engineError.repositoryChangedDuringAnalysis");
  if (normalized.includes("Target component was not found")) return t("engineError.targetComponentNotFound");
  if (normalized.includes("Target entrypoint was not found")) return t("engineError.targetEntrypointNotFound");
  if (normalized.includes("Target was not found")) return t("engineError.targetNotFound");
  if (normalized.includes("Project unit was not found")) return t("engineError.projectUnitNotFound");
  if (normalized.includes("Repository was not found")) return t("engineError.repositoryNotFound");
  if (normalized.includes("Workspace was not found")) return t("engineError.workspaceNotFound");
  return detail;
}
